import {createRequire} from 'node:module';
import {writeFile} from 'node:fs/promises';
const xlsx=createRequire(import.meta.url)('xlsx');
const book=xlsx.utils.book_new();
xlsx.utils.book_append_sheet(book,xlsx.utils.aoa_to_sheet([['Date','Start','Finish','Break','Absence','Total hours','Notes']]),'Daily Entries');
xlsx.utils.book_append_sheet(book,xlsx.utils.aoa_to_sheet([['Week Start','Week End','Total hours']]),'Weekly Totals');
const base64=xlsx.write(book,{type:'base64',bookType:'xlsx',compression:true});
await writeFile(new URL('../cloudflare-worker/src/pay-month-template.js',import.meta.url),`// Generated by tools/build-pay-month-template.mjs; contains no employee data.\nexport const blankPayMonthWorkbookBase64 = '${base64}';\n`);
