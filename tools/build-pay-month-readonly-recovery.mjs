import {readFileSync,writeFileSync} from 'node:fs';

const source=new URL('../power-platform/office-scripts/upsert-pay-month-register.ts',import.meta.url);
const tail=new URL('./templates/pay-month-readonly-recovery-main.ts',import.meta.url);
const output=new URL('../power-platform/office-scripts/verify-pay-month-register-readonly.ts',import.meta.url);
const original=readFileSync(source,'utf8'),boundary=original.indexOf('\nfunction write(');
if(boundary<0)throw new Error('The certified register helpers could not be located');
const helpers=original.slice(0,boundary).replace(/^\/\*[\s\S]*?\*\//,'/* Read-only recovery check. Generated by tools/build-pay-month-readonly-recovery.mjs. */');
const generated=helpers+'\n\n'+readFileSync(tail,'utf8');
if(process.argv.includes('--check')) {
  if(readFileSync(output,'utf8')!==generated)throw new Error('The read-only recovery script is out of date');
} else writeFileSync(output,generated);
